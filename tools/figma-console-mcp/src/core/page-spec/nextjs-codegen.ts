/**
 * Next.js code generator for page specs.
 *
 * Turns a PageSpec (see normalize.ts) into App Router source: a route file,
 * a page component, one component per top-level section (styled with a CSS
 * Module, or with Tailwind classes), a next/font setup, and the list of
 * assets to copy into public/. Every value in
 * the CSS comes straight from the spec, so the page renders at the design width
 * exactly as Figma laid it out; colors bound to Figma variables become CSS
 * custom properties scoped to the page root, so the theme stays editable.
 *
 * Pure: returns file contents and copy jobs; the tool does the disk I/O.
 */

import { createHash } from "node:crypto";
import { posix } from "node:path";
import type { PageSpec, SpecNode, SpecTextSegment } from "./normalize.js";
import { slug } from "./normalize.js";
import { cssToTailwind } from "./tailwind.js";

type Css = Record<string, string>;

export const GENERATED_MARKER = "@generated by figma-console-mcp";

export interface NextGenOptions {
	/** URL route, e.g. "/luyen-de/lam-bai" or "/". */
	route: string;
	/** Name for the component folder and page component (default: from the frame name). */
	pageName?: string;
	/** Project-relative app directory ("app" or "src/app"). */
	appDir: string;
	/** Project-relative directory the page component folder goes into. */
	componentsDir: string;
	/** Project-relative public directory. */
	publicDir: string;
	/** How fonts are loaded: next/font/google, next/font/local (files you add), or not at all. */
	fontSource: "google" | "local" | "none";
	/** Add data-figma-id attributes (for the pixel-diff step). */
	debugIds: boolean;
	/** CSS Modules (one .module.css per section) or Tailwind classes inline. Default css-modules. */
	styling?: "css-modules" | "tailwind";
	/**
	 * Sections shared between pages (Tailwind only), by section hash: the page imports
	 * them from `<componentsDir>/shared/` instead of writing its own copy.
	 */
	shared?: Map<string, SharedSection>;
	/** Spec asset file → file name in public/figma/assets/ (assets shared by content). */
	assetNames?: Map<string, string>;
	/** Match the project's conventions (file names, component declarations, imports). */
	codeStyle?: CodeStyle;
}

export interface CodeStyle {
	/** kebab-case file names (`site-header.tsx`) instead of the component name. */
	kebabFiles?: boolean;
	/** `export const X = (): React.JSX.Element => (…)` instead of `export function X()`. */
	arrowComponents?: boolean;
	/** Import across folders through this alias of the project root (e.g. "@/"), not ../ paths. */
	importAlias?: string;
}

/** File name (without extension) for a component, per the code style. */
export function codeFileBase(name: string, style?: CodeStyle): string {
	if (!style?.kebabFiles) return name;
	return name
		.replace(/([a-z0-9])([A-Z])/g, "$1-$2")
		.replace(/([A-Z]+)([A-Z][a-z])/g, "$1-$2")
		.toLowerCase();
}

/** A component that returns `jsx` (already indented for a return body). */
function componentSource(
	name: string,
	jsx: string,
	style: CodeStyle | undefined,
	exported = true,
): string {
	const exp = exported ? "export " : "";
	return style?.arrowComponents
		? `${exp}const ${name} = (): React.JSX.Element => (\n${jsx}\n);\n`
		: `${exp}function ${name}() {\n  return (\n${jsx}\n  );\n}\n`;
}

/** Import path from `fromDir` to `target` (both project-relative), per the code style. */
function importPath(
	fromDir: string,
	target: string,
	style?: CodeStyle,
): string {
	if (style?.importAlias) return `${style.importAlias}${target}`;
	const rel = posix.relative(fromDir, target);
	return rel.startsWith(".") ? rel : `./${rel}`;
}

export interface SharedSection {
	component: string;
	/** data-figma-id values of the shared file, in document order. */
	ids: string[];
}

/** One generated section, before it is written: enough to write it as a shared component. */
export interface SectionSource {
	nodeId: string;
	/** Same hash = same code (ignoring Figma ids): the section can be shared. */
	hash: string;
	ids: string[];
	jsx: string;
	usesImage: boolean;
	label: string;
	/** Component name it got on this page. */
	name: string;
}

export interface GeneratedFile {
	/** Project-relative path. */
	path: string;
	content: string;
}

export interface NextGenResult {
	files: GeneratedFile[];
	/** Asset copies: source file name inside the spec's assets dir → project-relative destination. */
	assets: { file: string; to: string }[];
	componentName: string;
	route: string;
	/** URL prefix the copied assets are served from, e.g. "/figma/home". */
	publicBase: string;
	/** Project-relative path of the page component (index.tsx). */
	pageFile: string;
	/** Figma section → generated component and file. */
	sections: { nodeId: string; component: string; file: string }[];
	/** Every section as generated for this page (shared or not). */
	sectionSources: SectionSource[];
	/** Figma id on this page → data-figma-id the shared components render instead. */
	idAlias: Record<string, string>;
	warnings: string[];
}

/** Source of a section component file. */
export function sectionFile(
	header: string,
	name: string,
	src: Pick<SectionSource, "jsx" | "usesImage" | "label">,
	cssModule: boolean,
	style?: CodeStyle,
): string {
	const imports = [
		...(src.usesImage ? ['import Image from "next/image";', ""] : []),
		...(cssModule
			? [`import styles from "./${codeFileBase(name, style)}.module.css";`, ""]
			: []),
	];
	return `${header}${imports.join("\n")}\n/** ${src.label} */\n${componentSource(name, src.jsx, style)}`;
}

export function generatedHeader(spec: PageSpec): string {
	return [
		`/* ${GENERATED_MARKER} (figma_generate_nextjs_page)`,
		` * Source: ${spec.source.fileName} › ${spec.source.pageName ?? "?"} › ${spec.source.nodeName} (${spec.source.nodeId})`,
		` * Exported: ${spec.source.exportedAt}. Re-running the generator overwrites this file. */`,
		"",
	].join("\n");
}

