interface Emitter {
	css: string[];
	tailwind: boolean;
	names: NameRegistry;
	ctx: CssCtx;
	opts: NextGenOptions;
	usesImage: boolean;
	warnings: string[];
	assetById: Map<
		string,
		{ url: string; fetched: boolean; width?: number; height?: number }
	>;
}

const TEXT_RESET: Css = { margin: "0" };

/** The className attribute for `css`: a CSS Module rule, or the Tailwind classes. */
function styled(em: Emitter, cls: string, css: Css): string {
	if (em.tailwind) return `className=${JSON.stringify(cssToTailwind(css))}`;
	em.css.push(rule(`.${cls}`, css));
	return `className={styles.${cls}}`;
}

function attrs(node: SpecNode, classAttr: string, em: Emitter): string {
	const parts = [classAttr];
	if (em.opts.debugIds) parts.push(`data-figma-id=${JSON.stringify(node.id)}`);
	return parts.join(" ");
}

function metaString(node: SpecNode, key: string): string | undefined {
	const v = node.meta?.[key];
	return typeof v === "string" && v ? v : undefined;
}

function linkOf(node: SpecNode): string | undefined {
	const fromMeta = metaString(node, "href");
	if (fromMeta) return fromMeta;
	for (const i of node.interactions ?? []) {
		for (const a of i.actions) {
			if (a.type === "URL" && typeof a.url === "string") return a.url;
		}
	}
	return undefined;
}

/**
 * Text of one run without line-end spaces. Figma never counts trailing spaces in a
 * text box's width; a browser with white-space: pre does, which would widen the box.
 */
export function visibleRun(segs: { characters: string }[], i: number): string {
	let t = segs[i].characters.replace(/[ \t\u00a0]+(?=\n)/g, "");
	const next = segs.slice(i + 1).find((s) => s.characters.length > 0);
	if (!next || next.characters.startsWith("\n"))
		t = t.replace(/[ \t\u00a0]+$/, "");
	return t;
}

function textChildren(
	node: SpecNode,
	cls: string,
	em: Emitter,
	pad: string,
): string {
	const text = node.text;
	if (!text) return "";
	// Only auto-width boxes drop line-end spaces: that is where Figma leaves them
	// out of the width. Fixed-width text keeps them (they can size a hug parent).
	const segs =
		text.autoResize === "WIDTH_AND_HEIGHT"
			? text.segments.map((seg, i, all) => ({
					...seg,
					characters: visibleRun(all, i),
				}))
			: text.segments;
	const lines: string[] = [];
	if (segs.length > 1) {
		segs.forEach((seg, i) => {
			const segAttr = styled(
				em,
				em.names.take(`${cls}Run`),
				finalizeCss(seg.css, em.ctx, segmentColorTokens(seg)),
			);
			const content = `{${JSON.stringify(seg.characters)}}`;
			lines.push(
				seg.href
					? `${pad}<a ${segAttr} href=${JSON.stringify(seg.href)}>${content}</a>`
					: `${pad}<span ${segAttr}>${content}</span>`,
			);
			if (seg.list && i === 0)
				em.warnings.push(
					`"${node.name}": list formatting is rendered as plain text.`,
				);
		});
	} else if (text.paragraphSpacing > 0 && segs[0].characters.includes("\n")) {
		const pCls = em.names.take(`${cls}Paragraph`);
		let pAttr = `className="block [&:not(:last-child)]:mb-[${text.paragraphSpacing}px]"`;
		if (!em.tailwind) {
			em.css.push(rule(`.${pCls}`, { display: "block" }));
			em.css.push(
				rule(`.${pCls}:not(:last-child)`, {
					"margin-bottom": `${text.paragraphSpacing}px`,
				}),
			);
			pAttr = `className={styles.${pCls}}`;
		}
		for (const para of segs[0].characters.split("\n")) {
			lines.push(`${pad}<span ${pAttr}>{${JSON.stringify(para)}}</span>`);
		}
	} else {
		const seg = segs[0];
		const content = `{${JSON.stringify(seg.characters)}}`;
		lines.push(
			seg?.href
				? `${pad}<a href=${JSON.stringify(seg.href)}>${content}</a>`
				: `${pad}${content}`,
		);
	}
	if (text.paragraphSpacing > 0 && segs.length > 1) {
		em.warnings.push(
			`"${node.name}": paragraph spacing with mixed text styles is not reproduced.`,
		);
	}
	// Vertically aligned text is a flex column: keep the runs on one line box.
	if (node.css.display === "flex") {
		const inner = pad.slice(2);
		return `${inner}<span>\n${lines.map((l) => `  ${l}`).join("\n")}\n${inner}</span>`;
	}
	return lines.join("\n");
}

function componentLabel(
	c: NonNullable<SpecNode["component"]>,
	props: string,
): string {
	// Variant names repeat the properties ("Size=24, State=On"): show the set instead.
	const label = c.set ? `Figma: ${c.set}${props}` : `Figma: ${c.name}${props}`;
	return label.replace(/\*\//g, "* /");
}

function emitNode(
	node: SpecNode,
	em: Emitter,
	depth: number,
	tagOverride?: string,
): string {
	const pad = "  ".repeat(depth);
	const cls = className(node, em.names);
	const tokens = nodeColorTokens(node);
	const css: Css = { ...node.css };
	let comment = "";
	if (node.component) {
		const c = node.component;
		const props = c.properties
			? ` (${Object.entries(c.properties)
					.map(([k, v]) => `${k}=${v}`)
					.join(", ")})`
			: "";
		comment = `${pad}{/* ${componentLabel(c, props)} */}\n`;
	}
	// The section root sits directly in `return (`: its label goes in the JSDoc instead.
	if (depth === 2) comment = "";

	if (node.asset) {
		const asset = em.assetById.get(node.asset);
		if (!asset) {
			em.warnings.push(
				`"${node.name}": asset ${node.asset} is missing from the spec.`,
			);
			return "";
		}
		if (!css.position) css.position = "relative";
		const boxAttr = styled(em, cls, finalizeCss(css, em.ctx, tokens));
		// Nothing to export (Figma: no visible layers): keep the box, empty.
		if (!asset.fetched)
			return `${comment}${pad}<div ${attrs(node, boxAttr, em)} />`;
		const rb = node.renderBounds ?? {
			x: 0,
			y: 0,
			width: node.box.width,
			height: node.box.height,
		};
		const imgAttr = styled(em, em.names.take(`${cls}Img`), {
			position: "absolute",
			left: `${rb.x}px`,
			top: `${rb.y}px`,
			width: `${rb.width}px`,
			height: `${rb.height}px`,
			"max-width": "none",
			display: "block",
		});
		em.usesImage = true;
		const alt = metaString(node, "alt") ?? "";
		const img =
			`${pad}  <Image ${imgAttr} src=${JSON.stringify(asset.url)} alt=${JSON.stringify(alt)} ` +
			`width={${Math.max(1, Math.round(rb.width))}} height={${Math.max(1, Math.round(rb.height))}} unoptimized />`;
		return `${comment}${pad}<div ${attrs(node, boxAttr, em)}>\n${img}\n${pad}</div>`;
	}

	if (node.text) {
		const tag = tagOverride ?? metaString(node, "tag") ?? "p";
		const textAttr = styled(
			em,
			cls,
			finalizeCss(
				{ ...TEXT_RESET, ...css },
				em.ctx,
				segmentColorTokens(node.text.segments[0]),
			),
		);
		const body = textChildren(node, cls, em, `${pad}  `);
		return `${comment}${pad}<${tag} ${attrs(node, textAttr, em)}>\n${body}\n${pad}</${tag}>`;
	}

	const href = linkOf(node);
	const tag = tagOverride ?? metaString(node, "tag") ?? (href ? "a" : "div");
	if (tag === "a") css["text-decoration"] = css["text-decoration"] ?? "none";
	const boxAttr = styled(em, cls, finalizeCss(css, em.ctx, tokens));
	const hrefAttr = tag === "a" && href ? ` href=${JSON.stringify(href)}` : "";
	const children = node.children
		.map((c) => emitNode(c, em, depth + 1))
		.filter(Boolean);
	if (children.length === 0)
		return `${comment}${pad}<${tag} ${attrs(node, boxAttr, em)}${hrefAttr} />`;
	return `${comment}${pad}<${tag} ${attrs(node, boxAttr, em)}${hrefAttr}>\n${children.join("\n")}\n${pad}</${tag}>`;
}

