function fontsFile(
	spec: PageSpec,
	opts: NextGenOptions,
	header: string,
): { content: string; vars: Map<string, string>; exports: string[] } {
	const vars = new Map<string, string>();
	const exports: string[] = [];
	const lines: string[] = [header];
	if (opts.fontSource === "none" || spec.fonts.length === 0) {
		lines.push(
			"/** Fonts are loaded by the app itself (fontSource: none). */",
			'export const fontVariables = "";',
			"",
		);
		return { content: lines.join("\n"), vars, exports };
	}
	const italicByFamily = new Map<string, boolean>();
	(function walk(n: SpecNode) {
		for (const s of n.text?.segments ?? [])
			if (s.font.italic) italicByFamily.set(s.font.family, true);
		n.children.forEach(walk);
	})(spec.tree);

	if (opts.fontSource === "google") {
		const imports = spec.fonts.map((f) => f.family.replace(/\s+/g, "_"));
		lines.push(`import { ${imports.join(", ")} } from "next/font/google";`, "");
		spec.fonts.forEach((f, i) => {
			const id = camel(f.family) || `font${i}`;
			const cssVar = `--font-${slug(f.family)}`;
			vars.set(f.family, cssVar);
			exports.push(id);
			const styles = italicByFamily.get(f.family)
				? '["normal", "italic"]'
				: '["normal"]';
			lines.push(
				`/** ${f.family}: ${f.styles.join(", ")} */`,
				`const ${id} = ${imports[i]}({`,
				`  weight: [${f.weights.map((w) => `"${w}"`).join(", ")}],`,
				`  style: ${styles},`,
				`  variable: "${cssVar}",`,
				`  display: "swap",`,
				`  preload: false,`,
				"});",
				"",
			);
		});
	} else {
		lines.push('import localFont from "next/font/local";', "");
		spec.fonts.forEach((f, i) => {
			const id = camel(f.family) || `font${i}`;
			const cssVar = `--font-${slug(f.family)}`;
			vars.set(f.family, cssVar);
			exports.push(id);
			const italic = italicByFamily.get(f.family);
			const src = f.weights.flatMap((w) =>
				[false, ...(italic ? [true] : [])].map(
					(it) =>
						`    { path: "./fonts/${slug(f.family)}-${w}${it ? "-italic" : ""}.woff2", weight: "${w}", style: "${it ? "italic" : "normal"}" },`,
				),
			);
			lines.push(
				`/** ${f.family}: put the exact font files Figma uses into ./fonts (same version = same text widths). */`,
				`const ${id} = localFont({`,
				"  src: [",
				...src,
				"  ],",
				`  variable: "${cssVar}",`,
				`  display: "swap",`,
				"});",
				"",
			);
		});
	}
	lines.push(
		`export const fontVariables = [${exports.map((e) => `${e}.variable`).join(", ")}].join(" ");`,
		"",
	);
	return { content: lines.join("\n"), vars, exports };
}

