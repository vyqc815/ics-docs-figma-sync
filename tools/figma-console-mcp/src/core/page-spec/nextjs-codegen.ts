export function generateNextPage(
	spec: PageSpec,
	opts: NextGenOptions,
): NextGenResult {
	const segments = routeSegments(opts.route);
	const baseName =
		opts.pageName ??
		spec.source.nodeName.replace(/^page:\s*\S*\s*/i, "").replace(/@\d+.*$/, "");
	const folder = slug(baseName) || "figma-page";
	let componentName = `${pascal(baseName) || "Figma"}Page`;
	if (/^\d/.test(componentName)) componentName = `Page${componentName}`;
	const compDir = posix.join(opts.componentsDir, folder);
	const style = opts.codeStyle;
	const pageDir = posix.join(opts.appDir, ...segments);
	const publicBase = `/figma/${folder}`;
	const warnings: string[] = [];

	const header = generatedHeader(spec);

	// Tokens → CSS custom properties on the page root.
	const colorVars = new Map<string, string>();
	const tokenValues = new Map<string, string>();
	for (const v of spec.tokens.variables) {
		if (v.type === "COLOR" && typeof v.value === "string") {
			colorVars.set(v.name, v.cssVariable);
			tokenValues.set(v.name, v.value);
		}
	}

	const assetUrls = new Map<string, string>();
	const assetById = new Map<
		string,
		{ url: string; fetched: boolean; width?: number; height?: number }
	>();
	const assets: { file: string; to: string }[] = [];
	let unexported = 0;
	for (const a of spec.assets) {
		const sharedName = opts.assetNames?.get(a.file);
		const url = sharedName
			? `/figma/assets/${sharedName}`
			: `${publicBase}/${a.file}`;
		assetUrls.set(a.url, url);
		assetById.set(a.id, {
			url,
			fetched: a.fetched,
			width: a.width,
			height: a.height,
		});
		if (a.fetched)
			assets.push({
				file: a.file,
				to: sharedName
					? posix.join(opts.publicDir, "figma", "assets", sharedName)
					: posix.join(opts.publicDir, "figma", folder, a.file),
			});
		else unexported++;
	}
	if (unexported)
		warnings.push(
			`${unexported} asset(s) were not exported (Figma found nothing visible to export, or the export was skipped); they render as empty boxes of the right size. Re-run figma_export_page_spec with outputDir if they should have content.`,
		);

	const fonts = fontsFile(spec, opts, header);
	const ctx: CssCtx = {
		colorVars,
		tokenValues,
		fontVars: fonts.vars,
		assetUrls,
	};
	const files: GeneratedFile[] = [];
	const tailwind = opts.styling === "tailwind";

	// Sections: each top-level child of the frame gets its own component (+ CSS Module),
	// unless an identical section is shared between pages.
	const sectionNames = new NameRegistry();
	const sectionFiles: NextGenResult["sections"] = [];
	const sectionSources: SectionSource[] = [];
	const idAlias: Record<string, string> = {};
	const sharedDir = posix.join(opts.componentsDir, "shared");
	const imports: string[] = [];
	const usedNames = new Set<string>();
	const sections = spec.tree.children.map((child, i) => {
		let name = pascal(child.name);
		if (!name || GENERIC_NAME.test(name) || /^\d/.test(name))
			name = `Section${i + 1}`;
		name = sectionNames.take(name);
		const em: Emitter = {
			css: [],
			tailwind,
			names: new NameRegistry(),
			ctx,
			opts,
			usesImage: false,
			warnings,
			assetById,
		};
		const jsx = emitNode(
			child,
			em,
			2,
			child.text || child.asset ? undefined : "section",
		);
		const props = child.component?.properties
			? ` (${Object.entries(child.component.properties)
					.map(([k, v]) => `${k}=${v}`)
					.join(", ")})`
			: "";
		const label = `Figma layer "${child.name.replace(/\*\//g, "")}"${
			child.component ? ` — ${componentLabel(child.component, props)}` : ""
		}`;
		const ids = [...jsx.matchAll(/data-figma-id="([^"]*)"/g)].map((m) => m[1]);
		const hash = createHash("sha1")
			.update(`${em.usesImage}|${jsx.replace(/ data-figma-id="[^"]*"/g, "")}`)
			.digest("hex")
			.slice(0, 16);
		sectionSources.push({
			nodeId: child.id,
			hash,
			ids,
			jsx,
			usesImage: em.usesImage,
			label,
			name,
		});

		const shared = tailwind ? opts.shared?.get(hash) : undefined;
		if (shared) {
			ids.forEach((id, k) => {
				if (shared.ids[k] && shared.ids[k] !== id) idAlias[id] = shared.ids[k];
			});
			let local = shared.component;
			if (usedNames.has(local)) local = `${shared.component}${i + 1}`;
			usedNames.add(local);
			const from = importPath(
				compDir,
				posix.join(sharedDir, codeFileBase(shared.component, style)),
				style,
			);
			imports.push(
				local === shared.component
					? `import { ${local} } from "${from}";`
					: `import { ${shared.component} as ${local} } from "${from}";`,
			);
			sectionFiles.push({
				nodeId: child.id,
				component: shared.component,
				file: posix.join(
					sharedDir,
					`${codeFileBase(shared.component, style)}.tsx`,
				),
			});
			return local;
		}

		usedNames.add(name);
		const base = codeFileBase(name, style);
		imports.push(`import { ${name} } from "./${base}";`);
		files.push({
			path: posix.join(compDir, `${base}.tsx`),
			content: sectionFile(
				header,
				name,
				{ jsx, usesImage: em.usesImage, label },
				!tailwind,
				style,
			),
		});
		if (!tailwind)
			files.push({
				path: posix.join(compDir, `${base}.module.css`),
				content: `${header}${em.css.join("\n")}`,
			});
		sectionFiles.push({
			nodeId: child.id,
			component: name,
			file: posix.join(compDir, `${base}.tsx`),
		});
		return name;
	});

	// Page root: frame box, token variables, box-sizing and smoothing to match Figma.
	const rootVars: Css = {};
	for (const v of spec.tokens.variables) {
		if (v.type === "COLOR" && typeof v.value === "string")
			rootVars[v.cssVariable] = v.value;
	}
	const rootCss = finalizeCss(
		{ ...spec.tree.css },
		ctx,
		nodeColorTokens(spec.tree),
	);
	delete rootCss.position;
	const rootStyle: Css = {
		...rootVars,
		position: "relative",
		margin: "0 auto",
		"-webkit-font-smoothing": "antialiased",
		"-moz-osx-font-smoothing": "grayscale",
		...rootCss,
	};
	const pageCss = [
		header,
		`/* Design tokens (Figma variables, resolved for this frame's mode) */\n`,
		rule(".root", rootStyle),
		"\n",
		rule(
			".root,\n.root :global(*),\n.root :global(*)::before,\n.root :global(*)::after",
			{ "box-sizing": "border-box" },
		),
	].join("");
	// Tailwind's preflight already makes every box border-box.
	if (!tailwind)
		files.push({
			path: posix.join(compDir, "page.module.css"),
			content: pageCss,
		});

	files.push({ path: posix.join(compDir, "fonts.ts"), content: fonts.content });

	const rootAttrs = [
		tailwind
			? `className={\`${cssToTailwind(rootStyle)} \${fontVariables}\`}`
			: `className={\`\${styles.root} \${fontVariables}\`}`,
	];
	if (opts.debugIds)
		rootAttrs.push(`data-figma-id=${JSON.stringify(spec.tree.id)}`);
	files.push({
		path: posix.join(compDir, "index.tsx"),
		content: [
			header,
			`import { fontVariables } from "./fonts";`,
			...(tailwind ? [] : [`import styles from "./page.module.css";`]),
			...imports,
			"",
			`/** Figma frame "${spec.source.nodeName}" — ${spec.frame.width}×${spec.frame.height}px. */`,
			componentSource(
				componentName,
				[
					`    <main ${rootAttrs.join(" ")}>`,
					...sections.map((s) => `      <${s} />`),
					"    </main>",
				].join("\n"),
				style,
			),
		].join("\n"),
	});

	files.push({
		path: posix.join(pageDir, "page.tsx"),
		content: [
			header,
			'import type { Metadata } from "next";',
			"",
			`import { ${componentName} } from "${importPath(pageDir, compDir, style)}";`,
			"",
			`export const metadata: Metadata = { title: ${JSON.stringify(spec.source.nodeName)} };`,
			"",
			...(style?.arrowComponents
				? [
						`const Page = (): React.JSX.Element => <${componentName} />;`,
						"",
						"export default Page;",
					]
				: [
						"export default function Page() {",
						`  return <${componentName} />;`,
						"}",
					]),
			"",
		].join("\n"),
	});

	if (opts.fontSource === "local") {
		warnings.push(
			`Add the font files listed in ${posix.join(compDir, "fonts.ts")} to ${posix.join(compDir, "fonts")}/ — use the same files Figma uses so text widths match.`,
		);
	}

	return {
		files,
		assets,
		componentName,
		route: `/${segments.join("/")}`,
		publicBase,
		pageFile: posix.join(compDir, "index.tsx"),
		sections: sectionFiles,
		sectionSources,
		idAlias,
		warnings,
	};
}
