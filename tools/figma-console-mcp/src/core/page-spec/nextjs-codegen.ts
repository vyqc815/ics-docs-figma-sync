interface CssCtx {
	colorVars: Map<string, string>; // token name → css var
	tokenValues: Map<string, string>; // token name → resolved color
	fontVars: Map<string, string>; // family → css var
	assetUrls: Map<string, string>; // spec url → public url
}

function tokenizeColors(css: Css, tokenNames: string[], ctx: CssCtx): Css {
	if (!tokenNames.length) return css;
	const out: Css = {};
	for (const [k, v] of Object.entries(css)) {
		let value = v;
		for (const name of tokenNames) {
			const cssVar = ctx.colorVars.get(name);
			const color = ctx.tokenValues.get(name);
			if (!cssVar || !color) continue;
			// Whole-value or exact color-token matches only, never substrings of other colors.
			const re = new RegExp(
				`(^|[\\s,(])${color.replace(/[()]/g, "\\$&")}(?=$|[\\s,)])`,
				"gi",
			);
			value = value.replace(re, (_m, pre) => `${pre}var(${cssVar}, ${color})`);
		}
		out[k] = value;
	}
	return out;
}

function finalizeCss(css: Css, ctx: CssCtx, tokenNames: string[]): Css {
	let out = { ...css };
	const family = out["font-family"]?.match(/^"(.+)"$/)?.[1];
	if (family && ctx.fontVars.has(family))
		out["font-family"] = `var(${ctx.fontVars.get(family)}), "${family}"`;
	for (const key of ["background", "background-image"]) {
		if (!out[key]) continue;
		out[key] = out[key].replace(/url\("([^"]+)"\)/g, (m, url) =>
			ctx.assetUrls.has(url) ? `url("${ctx.assetUrls.get(url)}")` : m,
		);
	}
	out = tokenizeColors(out, tokenNames, ctx);
	return out;
}

function rule(selector: string, css: Css): string {
	const body = Object.entries(css)
		.map(([k, v]) => `  ${k}: ${v};`)
		.join("\n");
	return `${selector} {\n${body}\n}\n`;
}

function nodeColorTokens(node: SpecNode): string[] {
	const t = node.tokens ?? {};
	const list = [
		...((t.fills as string[]) ?? []),
		...((t.strokes as string[]) ?? []),
	];
	return list.filter((x) => typeof x === "string");
}

function segmentColorTokens(seg: SpecTextSegment): string[] {
	const t = seg.tokens as Record<string, string | string[]> | undefined;
	const f = t?.fills;
	return Array.isArray(f) ? f : f ? [f] : [];
}

