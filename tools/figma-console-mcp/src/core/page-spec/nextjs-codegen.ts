function pascal(s: string): string {
	return slug(s)
		.split("-")
		.filter(Boolean)
		.map((w) => w[0].toUpperCase() + w.slice(1))
		.join("");
}

function camel(s: string): string {
	const p = pascal(s);
	return p ? p[0].toLowerCase() + p.slice(1) : "";
}

const GENERIC_NAME =
	/^(Frame|Group|Rectangle|Section|Vector|Ellipse|Instance|Component)\d*$/;

class NameRegistry {
	private used = new Map<string, number>();
	take(base: string): string {
		const n = (this.used.get(base) ?? 0) + 1;
		this.used.set(base, n);
		return n === 1 ? base : `${base}${n}`;
	}
}

function className(node: SpecNode, names: NameRegistry): string {
	let base = camel(node.name).slice(0, 32);
	if (!base || /^\d/.test(base) || GENERIC_NAME.test(pascal(node.name))) {
		base =
			node.role === "text"
				? "text"
				: node.role === "icon"
					? "icon"
					: node.role === "image"
						? "image"
						: "box";
	}
	return names.take(base);
}

export function routeSegments(route: string): string[] {
	const segs = route.split("/").filter(Boolean);
	for (const s of segs) {
		if (!/^[a-z0-9\-_.()[\]]+$/i.test(s)) {
			throw new Error(
				`Invalid route segment "${s}". Use URL-safe names, e.g. "/luyen-de/lam-bai".`,
			);
		}
	}
	return segs;
}

